const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),ts=require('typescript');
const exported={};
const code=ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/native/poiPagination.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{exports:exported});
const {appendPois,hasMorePois}=exported;
assert.equal(hasMorePois(null),false);
assert.equal(hasMorePois({page:1,pageSize:100,total:100}),false);
assert.equal(hasMorePois({page:1,pageSize:100,total:101}),true);
assert.equal(hasMorePois({page:2,pageSize:100,total:101}),false);
const first=Array.from({length:100},(_,i)=>({id:i+1,name:'Place '+(i+1),code:'P'+(i+1)}));
const next=[{id:100,name:'Updated',code:'P100'},{id:101,name:'Next',code:'P101'}];
const result=appendPois(first,next);
assert.equal(result.length,101);
assert.equal(result[99].name,'Updated');
assert.equal(result[100].id,101);
assert.equal(first[99].name,'Place 100');
assert.equal(appendPois(result,next).length,101);
assert.equal(appendPois(result,[]).length,101);
console.log('POI >100, page boundaries, overlap, repeated pages, empty page and immutable merge: PASS');
